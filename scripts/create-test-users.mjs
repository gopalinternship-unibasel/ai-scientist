// Creates two TEST users in the LOCAL Supabase stack and writes their
// credentials to .local-test-user.json (gitignored). Never run against a
// hosted project: it refuses any API URL that is not localhost.
//
//   tester  — a normal account (sign in, own runs, share, refine, feedback)
//   admin   — claims the admin role through the app's own bootstrap_first_admin()
//             RPC, which unlocks /admin (moderation, house-rule distillation,
//             eval harness)
//
// Inputs come from the environment (set by scripts/start-local.ps1 from
// `supabase status -o env`): SUPABASE_API_URL, SUPABASE_ANON_KEY,
// SUPABASE_SERVICE_ROLE_KEY. Nothing secret is printed.
//
// Usage: node scripts/create-test-users.mjs [--force]
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, ".local-test-user.json");
const force = process.argv.includes("--force");

const api = process.env.SUPABASE_API_URL;
const anon = process.env.SUPABASE_ANON_KEY;
const service = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!api || !anon || !service) {
  console.error("SUPABASE_API_URL, SUPABASE_ANON_KEY and SUPABASE_SERVICE_ROLE_KEY must be set (start-local.ps1 sets them).");
  process.exit(2);
}
if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(api.replace(/\/+$/, ""))) {
  console.error(`Refusing to create test users on a non-local API URL: ${api}`);
  process.exit(2);
}

const password = () => `T${randomBytes(12).toString("base64url")}9!`;

async function call(url, init) {
  const res = await fetch(url, init);
  const text = await res.text();
  let body = null;
  try { body = text ? JSON.parse(text) : null; } catch { body = text; }
  return { status: res.status, ok: res.ok, body };
}

async function findUser(email) {
  const r = await call(`${api}/auth/v1/admin/users?per_page=200`, {
    headers: { apikey: service, Authorization: `Bearer ${service}` },
  });
  const users = r.body?.users ?? [];
  return users.find((u) => u.email === email) ?? null;
}

async function ensureUser(email, pw) {
  const existing = await findUser(email);
  if (existing) {
    // Reset the password so the stored file is always valid.
    const r = await call(`${api}/auth/v1/admin/users/${existing.id}`, {
      method: "PUT",
      headers: { apikey: service, Authorization: `Bearer ${service}`, "Content-Type": "application/json" },
      body: JSON.stringify({ password: pw, email_confirm: true }),
    });
    if (!r.ok) throw new Error(`could not reset ${email}: ${r.status}`);
    return existing.id;
  }
  const r = await call(`${api}/auth/v1/admin/users`, {
    method: "POST",
    headers: { apikey: service, Authorization: `Bearer ${service}`, "Content-Type": "application/json" },
    body: JSON.stringify({ email, password: pw, email_confirm: true, user_metadata: { full_name: "Local Tester" } }),
  });
  if (!r.ok) throw new Error(`could not create ${email}: ${r.status} ${JSON.stringify(r.body)}`);
  return r.body.id;
}

async function signIn(email, pw) {
  const r = await call(`${api}/auth/v1/token?grant_type=password`, {
    method: "POST",
    headers: { apikey: anon, "Content-Type": "application/json" },
    body: JSON.stringify({ email, password: pw }),
  });
  if (!r.ok) throw new Error(`sign-in failed for ${email}: ${r.status}`);
  return r.body.access_token;
}

if (existsSync(outFile) && !force) {
  const cur = JSON.parse(readFileSync(outFile, "utf8"));
  // Validate the stored credentials still work (the DB may have been reset).
  try {
    await signIn(cur.tester.email, cur.tester.password);
    await signIn(cur.admin.email, cur.admin.password);
    console.log(`Test users already exist (${path.basename(outFile)}).`);
    process.exit(0);
  } catch {
    console.log("Stored test users no longer sign in; recreating.");
  }
}

const creds = {
  note: "TEST accounts for the LOCAL Supabase stack only (http://localhost:5180). Generated by scripts/create-test-users.mjs.",
  app_url: "http://localhost:5180/auth",
  tester: { email: "tester@ai-scientist.local.test", password: password() },
  admin: { email: "admin@ai-scientist.local.test", password: password() },
};

await ensureUser(creds.tester.email, creds.tester.password);
const adminId = await ensureUser(creds.admin.email, creds.admin.password);

// Grant admin through the app's own one-time bootstrap RPC (refuses once any
// admin exists). If another account already holds admin, fall back to a
// service-role insert so the test admin always works.
const adminToken = await signIn(creds.admin.email, creds.admin.password);
const boot = await call(`${api}/rest/v1/rpc/bootstrap_first_admin`, {
  method: "POST",
  headers: { apikey: anon, Authorization: `Bearer ${adminToken}`, "Content-Type": "application/json" },
  body: "{}",
});
if (boot.body !== true) {
  await call(`${api}/rest/v1/user_roles`, {
    method: "POST",
    headers: {
      apikey: service, Authorization: `Bearer ${service}`, "Content-Type": "application/json",
      Prefer: "resolution=ignore-duplicates",
    },
    body: JSON.stringify({ user_id: adminId, role: "admin" }),
  });
}

writeFileSync(outFile, JSON.stringify(creds, null, 2) + "\n", "utf8");
console.log(`Created test users ${creds.tester.email} and ${creds.admin.email} (admin); credentials in ${path.basename(outFile)}.`);
